"""Record installed backend dev dependency versions; run with backend/.venv Python."""

import subprocess
import sys
from pathlib import Path


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    result = subprocess.run(
        [sys.executable, "-m", "pip", "freeze"],
        capture_output=True,
        text=True,
        check=True,
    )
    lines = []
    for line in result.stdout.splitlines():
        if "==" not in line or "@" in line or line.startswith("-"):
            raise ValueError(
                "Lock generation requires versioned public packages, not editable/URL installs."
            )
        if line.lower().startswith("colorama=="):
            line += '; sys_platform == "win32"'
        lines.append(line)
    header = (
        "# Generated by scripts/lock_backend.py from the tested backend dev venv.\n"
        "# Direct/transitive versions; colorama is Windows-only. No private package URLs.\n"
    )
    (root / "backend/requirements-dev.lock").write_text(
        header + "\n".join(sorted(lines, key=str.lower)) + "\n", encoding="utf-8"
    )
    print("Recorded backend development versions; review/test before committing.")


if __name__ == "__main__":
    main()
